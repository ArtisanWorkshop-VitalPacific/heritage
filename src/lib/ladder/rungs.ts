export function getRung(n: number): Rung {
  const r = RUNGS.find((x) => x.n === n);
  if (!r) throw new Error(`No rung ${n}`);
  return r;
}

/** Short label for chips and boards, e.g. "10 · h". */
export function rungLabel(n: number): string {
  const r = RUNGS.find((x) => x.n === n);
  return r ? `${r.n} · ${r.short}` : String(n);
}

